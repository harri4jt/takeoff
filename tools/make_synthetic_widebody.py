"""Generate the SYNTHETIC aero and thrust tables for aircraft/generic_widebody_synthetic.

These numbers are invented, order-of-magnitude values for a fictional 4-engine
widebody. They are NOT data for any real airplane.

Lift:   CL_lin = CL0 + CLalpha * alpha, smoothly capped at CLmax by a log-sum-exp
        soft minimum, then a quadratic post-stall drop beyond alpha_stall.
Drag:   parabolic polar CD = CD0 + K CL^2, plus a quadratic post-stall rise.
Thrust: static thrust with a quadratic ram-drag lapse with airspeed.

Run:  python tools/make_synthetic_widebody.py
"""

from __future__ import annotations

import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "aircraft" / "generic_widebody_synthetic"

# --- synthetic aero parameters (takeoff flaps, gear down) ----------------------------
CL0 = 0.55  # CL at alpha = 0 with takeoff flaps
CLALPHA_PER_DEG = 0.09
CLMAX_NOMINAL = 1.90
SHARPNESS = 14.0  # soft-min sharpness (bigger = sharper knee)
ALPHA_STALL_DEG = 15.0
POST_STALL_DROP = 0.02  # CL loss per deg^2 beyond stall
CD0 = 0.040
K_INDUCED = 0.060  # ~ 1 / (pi e AR) with AR ~ 7, e ~ 0.75
POST_STALL_CD = 0.01  # CD rise per deg^2 beyond stall

# --- synthetic thrust (per engine) ---------------------------------------------------
T_STATIC_LBF = 50_000.0
LAPSE_1 = 0.0009  # per kt
LAPSE_2 = 1.2e-6  # per kt^2


def cl_of(alpha_deg: float) -> float:
    lin = CL0 + CLALPHA_PER_DEG * alpha_deg
    soft = -math.log(math.exp(-SHARPNESS * lin) + math.exp(-SHARPNESS * CLMAX_NOMINAL)) / SHARPNESS
    excess = max(0.0, alpha_deg - ALPHA_STALL_DEG)
    return soft - POST_STALL_DROP * excess**2


def cd_of(alpha_deg: float) -> float:
    cl = cl_of(alpha_deg)
    excess = max(0.0, alpha_deg - ALPHA_STALL_DEG)
    return CD0 + K_INDUCED * cl * cl + POST_STALL_CD * excess**2


def thrust_of(v_kts: float) -> float:
    return T_STATIC_LBF * (1.0 - LAPSE_1 * v_kts + LAPSE_2 * v_kts**2)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    header = (
        "# SYNTHETIC DATA - generated by tools/make_synthetic_widebody.py - NOT a real airplane\n"
    )
    with open(OUT / "aero_takeoff.csv", "w") as fh:
        fh.write(header)
        fh.write("alpha_deg,CL,CD\n")
        a = -10.0
        while a <= 24.0 + 1e-9:
            fh.write(f"{a:.1f},{cl_of(a):.5f},{cd_of(a):.5f}\n")
            a += 0.5
    with open(OUT / "thrust.csv", "w") as fh:
        fh.write(header)
        fh.write("airspeed_kts,thrust_lbf\n")
        for v in range(0, 301, 10):
            fh.write(f"{v},{thrust_of(v):.1f}\n")
    print(f"wrote tables to {OUT}")


if __name__ == "__main__":
    main()
